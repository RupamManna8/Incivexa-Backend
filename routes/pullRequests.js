import { Router } from 'express';
import mongoose from 'mongoose';
import { Investigation } from '../models/Investigation.js';
import { Incident } from '../models/Incident.js';
import { Project } from '../models/Project.js';
import { isDbConnected } from '../config/database.js';

function cleanRepoPath(rawPath) {
  if (!rawPath) return '';
  let clean = rawPath.replace(/\\/g, '/');
  if (clean.includes('demo-repo/')) {
    clean = clean.split('demo-repo/').pop();
  }
  return clean.replace(/^[A-Za-z]:\//, '').replace(/^\/+/, '');
}

function cleanDiff(diff) {
  if (!diff) return '';
  return diff.split('\n').map(line => {
    if (line.startsWith('--- a/')) {
      return `--- a/${cleanRepoPath(line.slice(6))}`;
    }
    if (line.startsWith('+++ b/')) {
      return `+++ b/${cleanRepoPath(line.slice(6))}`;
    }
    return line;
  }).join('\n');
}

export const router = Router({ mergeParams: true });

/**
 * GET /api/v1/projects/:projectId/pull-requests
 * Lists all generated pull requests for a project.
 */
router.get('/', async (req, res) => {
  const projectId = req.params.projectId || req.query.projectId;

  try {
    if (!isDbConnected() || !projectId || !mongoose.Types.ObjectId.isValid(projectId)) {
      return res.json({ pullRequests: [] });
    }

    const pid = new mongoose.Types.ObjectId(projectId);

    // Find project to check if it's demo-repo
    const project = await Project.findById(pid).lean();
    const isDemoProject = Boolean(project && (project.name === 'demo-repo' || project.repoUrl === 'demo-repo'));

    // Pull requests are investigations that have generated PRs
    const investigations = await Investigation.find({
      projectId: pid,
      confidence: 'HIGH',
      'suggestedFix.diff': { $exists: true, $ne: null },
      prUrl: { $exists: true, $ne: null }
    }).sort({ prCreatedAt: -1, createdAt: -1 }).lean();

    if (investigations.length === 0) {
      return res.json({ pullRequests: [], isDemoProject });
    }

    const incidentIds = investigations.map(i => i.incidentId).filter(id => mongoose.Types.ObjectId.isValid(id));
    const incidents = await Incident.find({ _id: { $in: incidentIds } }).lean();
    const incidentMap = new Map(incidents.map(inc => [inc._id.toString(), inc]));

    const pullRequests = investigations.map(inv => {
      const inc = incidentMap.get(inv.incidentId?.toString()) || {};
      const prStatus = inv.prStatus || (inv.fixStatus === 'MERGED' ? 'MERGED' : (inv.fixStatus === 'REJECTED' ? 'REJECTED' : 'OPEN'));
      const diff = cleanDiff(inv.suggestedFix?.diff || '');

      return {
        _id: inv._id.toString(),
        id: `PR-${inv.prNumber || inv._id.toString().slice(-4).toUpperCase()}`,
        prNumber: inv.prNumber,
        prUrl: inv.prUrl,
        title: `[Fix] ${inc.title || inv.rootCauseAnalysis?.summary || 'Automated defect remediation'}`,
        description: inv.suggestedFix?.description || inv.rootCauseAnalysis?.summary || 'Automated patch generated by Incivexa AI',
        branch: `aim/fix-${cleanRepoPath(inv.targetLocation?.filePath || 'patch').replace(/[^a-zA-Z0-9]/g, '-').slice(0, 30)}`,
        baseBranch: 'main',
        status: prStatus,
        fixStatus: inv.fixStatus || 'AWAITING_REVIEW',
        confidence: inv.confidenceScore ? Math.round(inv.confidenceScore * 100) : 95,
        diff,
        affectedFiles: (inv.suggestedFix?.affectedFiles || [inv.targetLocation?.filePath].filter(Boolean)).map(cleanRepoPath),
        targetLocation: {
          ...inv.targetLocation,
          filePath: cleanRepoPath(inv.targetLocation?.filePath)
        },
        rawIncidentId: (inc._id || inv.incidentId || '').toString(),
        incidentTitle: inc.title || 'Application Defect',
        author: 'Incivexa Autonomous SRE',
        createdAt: inv.prCreatedAt || inv.createdAt,
        updatedAt: inv.updatedAt,
        isDemo: isDemoProject || inv.repoUrl === 'demo-repo'
      };
    });

    return res.json({ pullRequests, isDemoProject });
  } catch (err) {
    console.error('[PullRequests] List error:', err);
    return res.status(500).json({ error: 'Internal Server Error', message: err.message });
  }
});

/**
 * POST /api/v1/projects/:projectId/pull-requests/:prId/merge
 * Merges the pull request, moves fix to MERGED, and marks incident RESOLVED.
 */
router.post('/:prId/merge', async (req, res) => {
  const { prId } = req.params;
  const { note } = req.body;

  try {
    if (!isDbConnected() || !mongoose.Types.ObjectId.isValid(prId)) {
      return res.status(400).json({ error: 'Database not connected or invalid PR ID' });
    }

    const inv = await Investigation.findById(prId);
    if (!inv) {
      return res.status(404).json({ error: 'Pull request investigation not found' });
    }

    inv.prStatus = 'MERGED';
    inv.fixStatus = 'MERGED';
    await inv.save();

    if (inv.incidentId && mongoose.Types.ObjectId.isValid(inv.incidentId)) {
      await Incident.findByIdAndUpdate(inv.incidentId, {
        $set: { status: 'RESOLVED' },
        $push: {
          timeline: {
            timestamp: new Date(),
            action: 'FIX_MERGED',
            actor: 'OPERATOR',
            message: note || `Pull Request PR-${inv.prNumber || prId.slice(-4).toUpperCase()} accepted & merged. Incident successfully resolved.`,
            metadata: { fixId: inv._id, prNumber: inv.prNumber, status: 'MERGED' }
          }
        }
      });
    }

    return res.json({
      success: true,
      status: 'MERGED',
      message: `Pull Request PR-${inv.prNumber || prId.slice(-4).toUpperCase()} merged successfully! Fix moved to Merged section and incident marked RESOLVED.`
    });
  } catch (err) {
    console.error('[PullRequests] Merge error:', err);
    return res.status(500).json({ error: err.message });
  }
});

